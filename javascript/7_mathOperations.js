// Math library

// round()

let decimalNumber = 4.7
const nearestInteger = Math.round(decimalNumber)
console.log(nearestInteger) // 5

// floor()

const nearestDownValue = Math.floor(decimalNumber)
console.log(nearestDownValue) // 4

// ceil()

console.log(Math.ceil(decimalNumber)) // 5

// pi()

console.log(Math.PI); // 3.1415

// random()

console.log(Math.random()) // 0 to 1 random numbers

// sqrt()

console.log(Math.sqrt(64)) // 8

// pow()

console.log(Math.pow(2, 10)) // 1024

// abs()

console.log(Math.abs(-20)) // 20



