// Basic Arithmetic Operations

// Addition

let sum = 5 + 3
console.log(sum) // 8

// Subtraction

let diff = 5 - 3
console.log(diff) // 2

// Concatenate

let conc = 5 + "3"
console.log(conc) // 53

// Multiplication

let prod = 5 * 3
console.log(prod) // 15

// Division

let div = 6 / 3
console.log(div) // 2

let div2 = 10 / 3
console.log(div2) // 3.333333

// Modulus % gives the remainder

let remain = 10 % 3
console.log(remain) // 1

// Exponential

let power = 2**3
console.log(power) // 8

let powerMath = Math.pow(2, 4)
console.log(powerMath) // 16

// Increment

let count = 1;
count++;
console.log(count) // 2

// Decrement
count--;
console.log(count) // 1




